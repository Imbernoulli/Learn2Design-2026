    def nearest_donors(self, topology: str, k: int = 8, interior_weight: float = 1.0,
                       loss_weight: float = 0.0, loss_floor: float = -1.0):
        """k donor topologies ranked by dist + loss_weight*max(loss, loss_floor).

        Data: random-topology NN distance ~7; deeply-optimized topologies reach
        0.17-0.42 while a median NN donor sits at 2.2 -> trading a little distance
        for much better donor loss pays off."""
