def build_group_mapping(problem):
    """Return (unit_mapping, inverse_unit_mapping) jnp-callables for the problem."""
    keys = [repr(p[1]).strip("'") for p in problem._optimization_pairs]
    lb = np.asarray(problem.bounds[0], dtype=np.float64)
    ub = np.asarray(problem.bounds[1], dtype=np.float64)
    is_log = np.array([k in LOG_PROPS for k in keys])
    log_lb = np.log(np.maximum(lb, 1e-300))
    log_ub = np.log(np.maximum(ub, 1e-300))
    log_span = log_ub - log_lb

    is_log_j = jnp.asarray(is_log)
    lb_j = jnp.asarray(lb)
    ub_j = jnp.asarray(ub)
    log_lb_j = jnp.asarray(log_lb)
    log_span_j = jnp.asarray(log_span)

    def unit_mapping(z):
        """z (R^n) -> normalized [0,1]^n such that bounded = lb + (ub-lb)*unit."""
        s = jax_sigmoid(z)
        # log group: bounded = exp(log_lb + log_span * s) ->
        # unit = (bounded - lb)/(ub - lb)
        u_log = (jnp.exp(log_lb_j + log_span_j * s) - lb_j) / (ub_j - lb_j)
        return jnp.where(is_log_j, u_log, s)

    def inverse_unit_mapping(u):
        """normalized [0,1]^n -> z in R^n (logit of the group's internal s)."""
        u = jnp.clip(u, 1e-12, 1 - 1e-12)
        bounded = lb_j + (ub_j - lb_j) * u
        s_log = (jnp.log(jnp.maximum(bounded, 1e-300)) - log_lb_j) / log_span_j
        s_log = jnp.clip(s_log, 1e-12, 1 - 1e-12)
        s = jnp.where(is_log_j, s_log, u)
        return jnp.log(s / (1 - s))

    return unit_mapping, inverse_unit_mapping


def jax_sigmoid(x):
    return 1.0 / (1.0 + jnp.exp(-x))


def _position_groups(pairs) -> np.ndarray:
    """Group param indices by first grid position found in the component name(s)."""
    import re

    groups = {}
    gids = np.zeros(len(pairs), dtype=np.int32)
    for i, pr in enumerate(pairs):
        comp = repr(pr[0])
        toks = re.findall(r"\d{2}", comp)
        g = toks[0] if toks else "zz"
        if g not in groups:
            groups[g] = len(groups)
        gids[i] = groups[g]
    return gids


