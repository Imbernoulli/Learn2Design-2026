    def transplant_composite(self, target_problem, donors,
                             fill: str = "donor_sibling") -> np.ndarray:
        """Multi-donor composite transplant: for each target key, copy from the
        nearest donor (ranked order) that HAS the key; still-missing keys fall
        back to the union same-property pool across donors, else midpoint.

        Rationale: single-donor transplants leave ~10% of params (the components
        where topologies differ) to heuristic fill; those params have no joint
        structure to preserve from that donor anyway, so borrowing the matching
        key from the next-nearest donor that owns it should raise fidelity.
        """
        tgt_keys = problem_pair_keys(target_problem)
        lb, ub = [np.asarray(b, dtype=np.float64) for b in target_problem.bounds]
        kvs = []
        prop_pool: dict[str, list[float]] = {}
        for topo, _dist, _dloss, eidx in donors:
            _, kv = self._donor_key_values(topo, eidx)
            kvs.append(kv)
            for k, v in kv.items():
                prop_pool.setdefault(k.split("|")[1].strip("'"), []).append(v)
        out = np.empty(len(tgt_keys), dtype=np.float64)
        n_copied = 0
        for i, k in enumerate(tgt_keys):
            val = None
            for kv in kvs:
                v = kv.get(k)
                if v is not None:
                    val = v
                    break
            if val is None:
                prop = k.split("|")[1].strip("'")
                pool = prop_pool.get(prop)
                if fill == "donor_sibling" and pool:
                    val = float(np.median(pool))
                else:
                    val = 0.5 * (lb[i] + ub[i])
            else:
                n_copied += 1
            out[i] = float(np.clip(val, lb[i], ub[i]))
        self.last_fill_ratio = n_copied / max(len(tgt_keys), 1)
        return out

    def transplant(self, target_problem, donor_topology: str, entry_idx: int,
                   fill: str = "donor_sibling", aux_kvs=None) -> np.ndarray:
        """Build a bounded param vector for target_problem from the donor entry.

        Missing keys (mostly boundary components that differ) are filled from the
        donor's same-property values at other positions (donor_sibling), else
        bounds midpoint. When aux_kvs (list of {pair_key: value} from other
        near donors) is given, a missing key is first borrowed from the nearest
        aux donor that owns it (composite fill) before the sibling heuristic.
        """
        _, donor_kv = self._donor_key_values(donor_topology, entry_idx)
        # donor property -> values pool (for sibling fill)
        prop_pool: dict[str, list[float]] = {}
        for k, v in donor_kv.items():
            prop = k.split("|")[1].strip("'")
            prop_pool.setdefault(prop, []).append(v)

        tgt_keys = problem_pair_keys(target_problem)
        lb, ub = [np.asarray(b, dtype=np.float64) for b in target_problem.bounds]
        out = np.empty(len(tgt_keys), dtype=np.float64)
        n_copied = 0
        for i, k in enumerate(tgt_keys):
            if k in donor_kv:
                out[i] = donor_kv[k]
                n_copied += 1
            else:
                val = None
                if aux_kvs:
                    for akv in aux_kvs:
                        v = akv.get(k)
                        if v is not None:
                            val = v
                            n_copied += 1
                            break
                if val is None:
                    if fill == "elite":
                        em = self.elite_key_medians()
                        if em is not None:
                            val = em.get(k)
                    if val is None:
                        prop = k.split("|")[1].strip("'")
                        pool = prop_pool.get(prop)
                        if fill != "midpoint" and pool:
                            val = float(np.median(pool))
                        else:
                            val = 0.5 * (lb[i] + ub[i])
                out[i] = val
            out[i] = float(np.clip(out[i], lb[i], ub[i]))
        self.last_fill_ratio = n_copied / max(len(tgt_keys), 1)
        return out


