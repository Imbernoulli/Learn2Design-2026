    def _load_index(self, obj: Objective):
        """Instance-independent: load the dataset index (no objective info used).

        size=None: the index covers all size classes and donors are matched by
        topology-string length at query time, so nothing is read from the
        evaluation problem before start_logging (submission-rules compliance).
        """
